package main

import (
	"fmt"
	"math"
	"regexp"
	"strconv"
	"strings"
	"time"
)

const (
	headerStart = ";Header Start"
	headerEnd   = ";Header End"

	// Cosmetic fields copied from IVI 3licer output (tolerated by IVI firmware).
	cosmeticTimeS     = "17368.24"
	cosmeticWorkSpeed = "4800"
)

var (
	reAxis         = regexp.MustCompile(`([XYZ])(-?\d+(?:\.\d+)?)`)
	reTemp         = regexp.MustCompile(`\bS(\d+(?:\.\d+)?)`)
	reNozzleHdr    = regexp.MustCompile(`;nozzle_temperature\(°C\):\s*([\d.]+)`)
	reBedHdr       = regexp.MustCompile(`;build_plate_temperature\(°C\):\s*([\d.]+)`)
	reMaterialHdr  = regexp.MustCompile(`;material_type:\s*(\S+)`)
	reFilamentCfg  = regexp.MustCompile(`(?m)^;\s*filament_type\s*=\s*(\S+)`)
	reM82         = regexp.MustCompile(`^M82\b`)
	reM73         = regexp.MustCompile(`^M73\b`)
	reTotalLines  = regexp.MustCompile(`^;file_total_lines:\s*\d+`)
	reEstTime     = regexp.MustCompile(`(?m)^;\s*(?:estimated printing time \(normal mode\)\s*=|total estimated time:\s*)(.+)$`)
	reTimePart    = regexp.MustCompile(`(\d+)\s*([dhms])`)
	reLayerHeight = regexp.MustCompile(`(?m)^;\s*layer_height\s*=\s*([\d.]+)`)
	reFilamentMM  = regexp.MustCompile(`(?m)^;\s*(?:filament used \[mm\]\s*=|total filament length \[mm\]\s*:)\s*([\d.]+)`)
	reExtrudeE    = regexp.MustCompile(`\bE(-?\d+(?:\.\d+)?)`)
	skipAfterHdr  = map[string]bool{
		";G-code for 3dp engraving": true,
		";Generated by IVI 3licer":  true,
	}
)

// parseDurationSeconds parses OrcaSlicer duration strings such as
// "1d 2h 16m 12s", "2h 16m 12s", "16m 42s", or "45s" into total seconds.
func parseDurationSeconds(s string) (float64, bool) {
	matches := reTimePart.FindAllStringSubmatch(strings.ToLower(s), -1)
	if len(matches) == 0 {
		return 0, false
	}
	var total float64
	for _, m := range matches {
		v, err := strconv.ParseFloat(m[1], 64)
		if err != nil {
			continue
		}
		switch m[2] {
		case "d":
			total += v * 86400
		case "h":
			total += v * 3600
		case "m":
			total += v * 60
		case "s":
			total += v
		}
	}
	return total, total > 0
}

// GCodeMeta summarizes the metadata extracted/generated during G-code transformation.
type GCodeMeta struct {
	Transformed    bool    `json:"transformed"`
	AlreadyReady   bool    `json:"already_ready"`
	TotalLines     int     `json:"total_lines"`
	ValidLines     int     `json:"valid_lines"`
	StrippedM73    int     `json:"stripped_m73"`
	Material       string  `json:"material"`
	NozzleTemp     string  `json:"nozzle_temp"`
	BedTemp        string  `json:"bed_temp"`
	MinX           float64 `json:"min_x"`
	MaxX           float64 `json:"max_x"`
	MinY           float64 `json:"min_y"`
	MaxY           float64 `json:"max_y"`
	MinZ           float64  `json:"min_z"`
	MaxZ           float64  `json:"max_z"`
	Warnings       []string `json:"warnings,omitempty"`
}

// checkPrimeBalance inspects the start/end G-code sections for a large
// end-of-print retraction (>= 4.0 mm, e.g. G1 E-6.5) without a compensating
// stationary start-of-print re-prime (G1 E+<mm> with no X/Y motion) before the
// intro line. It is strictly non-destructive (advisory warning only) so custom
// calibration prints are never modified or blocked.
func checkPrimeBalance(lines []string) []string {
	inStart, inEnd := false, false
	hasStartPrime := false
	maxEndRetract := 0.0

	for _, raw := range lines {
		s := strings.TrimSpace(raw)
		lower := strings.ToLower(s)
		if strings.HasPrefix(lower, ";start gcode begin") {
			inStart = true
			continue
		}
		if strings.HasPrefix(lower, ";start gcode end") {
			inStart = false
			continue
		}
		if strings.HasPrefix(lower, ";end gcode begin") {
			inEnd = true
			continue
		}
		if strings.HasPrefix(lower, ";end of gcode") {
			inEnd = false
			continue
		}
		if s == "" || strings.HasPrefix(s, ";") {
			continue
		}
		code := s
		if idx := strings.IndexByte(code, ';'); idx >= 0 {
			code = strings.TrimSpace(code[:idx])
		}
		if !strings.HasPrefix(code, "G1 ") && !strings.HasPrefix(code, "G0 ") {
			continue
		}
		m := reExtrudeE.FindStringSubmatch(code)
		if len(m) != 2 {
			continue
		}
		eVal, err := strconv.ParseFloat(m[1], 64)
		if err != nil {
			continue
		}
		if inStart && eVal >= 3.0 && !strings.Contains(code, "X") && !strings.Contains(code, "Y") {
			hasStartPrime = true
		}
		if inEnd && eVal <= -4.0 {
			if -eVal > maxEndRetract {
				maxEndRetract = -eVal
			}
		}
	}

	if maxEndRetract >= 4.0 && !hasStartPrime {
		return []string{
			fmt.Sprintf("end-of-print retracts %.1fmm but start G-code has no stationary re-prime before intro line (check OrcaSlicer preset or stale .opc cache)", maxEndRetract),
		}
	}
	return nil
}

func firstTemp(lines []string, codes ...string) string {
	codeSet := make(map[string]bool, len(codes))
	for _, c := range codes {
		codeSet[c] = true
	}
	for _, ln := range lines {
		s := strings.TrimSpace(ln)
		if s == "" || strings.HasPrefix(s, ";") {
			continue
		}
		fields := strings.Fields(s)
		if len(fields) == 0 || !codeSet[fields[0]] {
			continue
		}
		rest := s[len(fields[0]):]
		if m := reTemp.FindStringSubmatch(rest); len(m) == 2 {
			return m[1]
		}
	}
	return ""
}

func computeBounds(lines []string) (minX, maxX, minY, maxY, minZ, maxZ float64) {
	seenX, seenY, seenZ := false, false, false
	inStart := false
	for _, ln := range lines {
		s := strings.TrimSpace(ln)
		if strings.Contains(s, ";Start GCode begin") {
			inStart = true
			continue
		}
		if strings.Contains(s, ";Start GCode end") {
			inStart = false
			continue
		}
		if inStart || s == "" || strings.HasPrefix(s, ";") {
			continue
		}
		fields := strings.Fields(s)
		if len(fields) == 0 || (fields[0] != "G0" && fields[0] != "G1") {
			continue
		}
		rest := s[len(fields[0]):]
		matches := reAxis.FindAllStringSubmatch(rest, -1)
		for _, m := range matches {
			v, err := strconv.ParseFloat(m[2], 64)
			if err != nil {
				continue
			}
			switch m[1] {
			case "X":
				if !seenX {
					minX, maxX, seenX = v, v, true
				} else {
					minX = math.Min(minX, v)
					maxX = math.Max(maxX, v)
				}
			case "Y":
				if !seenY {
					minY, maxY, seenY = v, v, true
				} else {
					minY = math.Min(minY, v)
					maxY = math.Max(maxY, v)
				}
			case "Z":
				if !seenZ {
					minZ, maxZ, seenZ = v, v, true
				} else {
					minZ = math.Min(minZ, v)
					maxZ = math.Max(maxZ, v)
				}
			}
		}
	}
	return
}

func fmtFloat(v float64) string {
	return strconv.FormatFloat(v, 'g', -1, 64)
}

func countValidLines(lines []string) int {
	n := 0
	for _, ln := range lines {
		s := strings.TrimSpace(ln)
		if s != "" && !strings.HasPrefix(s, ";") {
			n++
		}
	}
	return n
}

// TransformGCode promotes OrcaSlicer's embedded Luban `;Header Start` block to
// line 1, strips OrcaSlicer's preamble comments and any stray M73 lines, and
// populates line counts, temperatures, and bounding-box metadata required by
// the IVI firmware.
//
// If the file already starts with `;Header Start` and already contains
// `;file_total_lines:`, it is returned untouched (idempotent).
func TransformGCode(raw []byte, now time.Time) ([]byte, GCodeMeta, error) {
	normalized := strings.ReplaceAll(string(raw), "\r\n", "\n")
	lines := strings.Split(normalized, "\n")

	// Locate ;Header Start .. ;Header End
	hs, he := -1, -1
	for i, ln := range lines {
		if strings.Contains(ln, headerStart) {
			hs = i
			break
		}
	}
	if hs >= 0 {
		for i := hs; i < len(lines); i++ {
			if strings.Contains(lines[i], headerEnd) {
				he = i
				break
			}
		}
	}

	// Already transformed?
	if hs == 0 && he > 0 {
		hasTotals := false
		for i := hs; i <= he; i++ {
			if reTotalLines.MatchString(strings.TrimSpace(lines[i])) {
				hasTotals = true
				break
			}
		}
		if hasTotals {
			oldHdr := strings.Join(lines[hs:he+1], "\n")
			meta := GCodeMeta{
				Transformed:  false,
				AlreadyReady: true,
				TotalLines:   len(lines),
				ValidLines:   countValidLines(lines),
				Material:     "PLA",
			}
			if m := reNozzleHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
				meta.NozzleTemp = m[1]
			}
			if m := reBedHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
				meta.BedTemp = m[1]
			}
			if m := reMaterialHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
				meta.Material = m[1]
			}
			meta.MinX, meta.MaxX, meta.MinY, meta.MaxY, meta.MinZ, meta.MaxZ = computeBounds(lines[he+1:])
			return raw, meta, nil
		}
	}

	if hs < 0 || he < 0 {
		// No Luban header found — return untouched but report metadata.
		meta := GCodeMeta{
			Transformed: false,
			TotalLines:  len(lines),
			ValidLines:  countValidLines(lines),
		}
		return raw, meta, nil
	}

	// Find leading M82 before header.
	m82 := "M82 ;absolute extrusion mode"
	for _, ln := range lines[:hs] {
		s := strings.TrimSpace(ln)
		if reM82.MatchString(s) {
			m82 = s
			break
		}
	}

	// Body starts after old header, skipping blank lines and duplicate trailer comments.
	tail := he + 1
	for tail < len(lines) {
		s := strings.TrimSpace(lines[tail])
		if s == "" || skipAfterHdr[s] {
			tail++
			continue
		}
		break
	}

	// Filter out any stray M73 lines (IVI firmware halts on M73).
	rawBody := lines[tail:]
	body := make([]string, 0, len(rawBody))
	strippedM73 := 0
	for _, ln := range rawBody {
		if reM73.MatchString(strings.TrimSpace(ln)) {
			strippedM73++
			continue
		}
		body = append(body, ln)
	}

	oldHdr := strings.Join(lines[hs:he+1], "\n")
	nozzle := ""
	bed := ""
	if m := reNozzleHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
		nozzle = m[1]
	}
	if m := reBedHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
		bed = m[1]
	}
	if nozzle == "" {
		nozzle = firstTemp(body, "M109", "M104")
	}
	if bed == "" {
		bed = firstTemp(body, "M140", "M190")
	}

	material := "PLA"
	if m := reMaterialHdr.FindStringSubmatch(oldHdr); len(m) == 2 {
		material = m[1]
	} else if m := reFilamentCfg.FindStringSubmatch(strings.Join(body, "\n")); len(m) == 2 {
		material = strings.Trim(m[1], `"`)
	}

	minX, maxX, minY, maxY, minZ, maxZ := computeBounds(body)

	// Extract real estimated printing time, layer height, and filament length
	// from OrcaSlicer's header/footer comments (falling back to safe defaults).
	estTimeSec := 0.0
	hasEstTime := false
	if m := reEstTime.FindStringSubmatch(normalized); len(m) == 2 {
		estTimeSec, hasEstTime = parseDurationSeconds(m[1])
	}
	timeIntStr := "6666"
	estTimeStr := cosmeticTimeS
	if hasEstTime {
		timeIntStr = strconv.Itoa(int(math.Round(estTimeSec)))
		estTimeStr = fmt.Sprintf("%.2f", estTimeSec)
	}
	layerHeightStr := "0.2"
	if m := reLayerHeight.FindStringSubmatch(normalized); len(m) == 2 {
		layerHeightStr = m[1]
	}
	filamentUsedStr := "0m"
	if m := reFilamentMM.FindStringSubmatch(normalized); len(m) == 2 {
		if mm, err := strconv.ParseFloat(m[1], 64); err == nil && mm > 0 {
			filamentUsedStr = fmt.Sprintf("%.2fm", mm/1000.0)
		}
	}

	hdr := []string{
		headerStart,
		"",
		";FLAVOR:Marlin",
		fmt.Sprintf(";TIME:%s", timeIntStr),
		fmt.Sprintf(";Filament used: %s", filamentUsedStr),
		fmt.Sprintf(";Layer height: %s", layerHeightStr),
		"",
		"",
		";header_type: 3dp,0.3mm",
		";file_total_lines: 0", // patched below (index 9)
		";file_valid_lines: 0", // patched below (index 10)
		fmt.Sprintf(";estimated_time(s): %s", estTimeStr),
		fmt.Sprintf(";material_type: %s", material),
	}
	if nozzle != "" {
		hdr = append(hdr, fmt.Sprintf(";nozzle_temperature(°C): %s", nozzle))
	}
	if bed != "" {
		hdr = append(hdr, fmt.Sprintf(";build_plate_temperature(°C): %s", bed))
	}
	hdr = append(hdr,
		fmt.Sprintf(";work_speed(mm/minute): %s", cosmeticWorkSpeed),
		fmt.Sprintf(";max_x(mm): %s", fmtFloat(maxX)),
		fmt.Sprintf(";max_y(mm): %s", fmtFloat(maxY)),
		fmt.Sprintf(";max_z(mm): %s", fmtFloat(maxZ)),
		fmt.Sprintf(";min_x(mm): %s", fmtFloat(minX)),
		fmt.Sprintf(";min_y(mm): %s", fmtFloat(minY)),
		fmt.Sprintf(";min_z(mm): %s", fmtFloat(minZ)),
		"",
		headerEnd,
		"",
		";G-code for 3dp engraving",
		";Generated by IVI 3licer",
		";"+now.Format("Mon Jan 02 2006 15:04:05"),
		"",
		m82,
	)

	out := make([]string, 0, len(hdr)+len(body))
	out = append(out, hdr...)
	out = append(out, body...)

	total := len(out)
	valid := countValidLines(out)
	out[9] = fmt.Sprintf(";file_total_lines: %d", total)
	out[10] = fmt.Sprintf(";file_valid_lines: %d", valid)

	meta := GCodeMeta{
		Transformed: true,
		TotalLines:  total,
		ValidLines:  valid,
		StrippedM73: strippedM73,
		Material:    material,
		NozzleTemp:  nozzle,
		BedTemp:     bed,
		MinX:        minX,
		MaxX:        maxX,
		MinY:        minY,
		MaxY:        maxY,
		MinZ:        minZ,
		MaxZ:        maxZ,
		Warnings:    checkPrimeBalance(body),
	}
	return []byte(strings.Join(out, "\n")), meta, nil
}
